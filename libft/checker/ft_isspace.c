/*
Checks if a character is a space (' ', '\t', '\r'), returns 1 if it is,
otherwise 0.
*/
int	ft_isspace(int c)
{
	return ((c == ' ') | ((unsigned)(c - '\t') <= ('\r' - '\t')));
}
